CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 role VARCHAR(16) NOT NULL,
 password_hash VARCHAR(100) NOT NULL DEFAULT '',
 created_at DATETIME(3) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY, account_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME(3) NOT NULL, created_at DATETIME(3) NOT NULL,
 INDEX idx_session_account(account_id), INDEX idx_session_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sms_codes (
 phone VARCHAR(32) PRIMARY KEY, digest CHAR(64) NOT NULL,
 salt VARCHAR(64) NOT NULL, expires_at DATETIME(3) NOT NULL,
 sent_at DATETIME(3) NOT NULL, attempts INT NOT NULL DEFAULT 0,
 used TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS halls (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL, name_en VARCHAR(100) NOT NULL,
 slug VARCHAR(64) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 hall_id BIGINT UNSIGNED NOT NULL DEFAULT 1,
 parent_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 name VARCHAR(100) NOT NULL, name_en VARCHAR(100) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, enabled TINYINT(1) NOT NULL DEFAULT 1,
 INDEX idx_category_parent(parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS regions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL, name_en VARCHAR(150) NOT NULL DEFAULT '',
 enabled TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS contents (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 kind VARCHAR(16) NOT NULL, owner_id BIGINT UNSIGNED NOT NULL,
 vendor_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 vendor_owner_key BIGINT UNSIGNED NULL UNIQUE,
 published_revision_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 draft_revision_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 epoch BIGINT UNSIGNED NOT NULL DEFAULT 0,
 visible TINYINT(1) NOT NULL DEFAULT 0,
 featured TINYINT(1) NOT NULL DEFAULT 0,
 sort_order INT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL, updated_at DATETIME(3) NOT NULL,
 INDEX idx_content_owner(owner_id,kind),
 INDEX idx_content_vendor(vendor_id,visible),
 INDEX idx_content_public(kind,visible,featured,sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS revisions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 content_id BIGINT UNSIGNED NOT NULL, base_epoch BIGINT UNSIGNED NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'draft',
 name VARCHAR(200) NOT NULL, name_en VARCHAR(200) NOT NULL DEFAULT '',
 keywords VARCHAR(500) NOT NULL DEFAULT '',
 main_products VARCHAR(500) NOT NULL DEFAULT '',
 region_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 category_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 payload LONGTEXT NOT NULL,
 review_note VARCHAR(1000) NOT NULL DEFAULT '',
 reviewer_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 reviewed_at DATETIME(3) NULL,
 created_at DATETIME(3) NOT NULL, updated_at DATETIME(3) NOT NULL,
 INDEX idx_revision_status(status,created_at),
 INDEX idx_revision_content(content_id),
 INDEX idx_revision_region(region_id), INDEX idx_revision_category(category_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS media (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL, path VARCHAR(255) NOT NULL,
 thumb_path VARCHAR(255) NOT NULL,
 created_at DATETIME(3) NOT NULL, INDEX idx_media_owner(owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS media_references (
 revision_id BIGINT UNSIGNED NOT NULL, media_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(revision_id,media_id), INDEX idx_media_reference(media_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS review_logs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 content_id BIGINT UNSIGNED NOT NULL, revision_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL, action VARCHAR(32) NOT NULL,
 note VARCHAR(1000) NOT NULL DEFAULT '', created_at DATETIME(3) NOT NULL,
 INDEX idx_review_content(content_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
